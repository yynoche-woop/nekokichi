  weight: string; // 例「オス4〜6kg・メス3〜5kg(目安)」
  grown?: { years: number; text: string }; // 成長がゆっくりな猫種だけ。features の記述(同じ出典)を要約。ツール(年齢・体型・ごはん)の補足に使う
