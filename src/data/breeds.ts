  lead: string; // 紹介文
  features: { t: string; d: string }[]; // 確かな特徴
  coats?: { t: string; d: string }[]; // 毛色・模様の呼び名(t=呼び名、d=説明)。検索される呼び名をそのまま書く。共通の呼び名はコラム /columns/coat-patterns/ にまとめる
