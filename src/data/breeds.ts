  tendency: { play: 1 | 2 | 3 | 4 | 5; cuddle: 1 | 2 | 3 | 4 | 5; groom: 1 | 2 | 3 | 4 | 5; voice: 1 | 2 | 3 | 4 | 5; size: 1 | 2 | 3 | 4 | 5 }; // よく言われる傾向(猫種診断用)
